#ifndef _GNU_SOURCE
#define _GNU_SOURCE
#endif
#include <audio_math/float_sqrt.h>
#include <inttypes.h>
#include <math.h>
#include <stdio.h>
#include <string.h>
#ifdef _WIN32
#include <windows.h>
#else
#include <time.h>
#endif

static double (*volatile reference)(double) = sqrt;
/* Retain the system square-root entry for speed/local-stack comparison. */
static double baseline_sqrt(double value) {
    return sqrt(value);
}
static double (*volatile functions[3])(double) = {baseline_sqrt, audio_math_sqrt_f64, audio_math_sqrt_soft_f64};
static uint64_t state = UINT64_C(0x572b194d);
static uint64_t checks;
static volatile uint64_t consumed;
static double inputs[1024];

/* Generate reproducible full-width input patterns. */
static uint64_t random_bits(void) {
    state ^= state << 13;
    state ^= state >> 7;
    state ^= state << 17;
    return state;
}
/* Compare system, common hardware, and pure-C double results bitwise. */
static int check_value(uint64_t bits) {
    double value = audio_math_float64_from_bits(bits);
    uint64_t expected = audio_math_float64_bits(reference(value));
    uint64_t actual = audio_math_float64_bits(functions[1](value));
    uint64_t software = audio_math_float64_bits(functions[2](value));
    ++checks;
    if (expected != actual || expected != software) {
        printf("FAIL input=%016" PRIx64 " expected=%016" PRIx64 " actual=%016" PRIx64
               " software=%016" PRIx64 "\n",
               bits, expected, actual, software);
        return 0;
    }
    return 1;
}
/* Read host monotonic time outside product implementation. */
static double now_seconds(void) {
#ifdef _WIN32
    LARGE_INTEGER ticks, frequency;
    QueryPerformanceCounter(&ticks);
    QueryPerformanceFrequency(&frequency);
    return (double)ticks.QuadPart / frequency.QuadPart;
#else
    struct timespec ticks;
    clock_gettime(CLOCK_MONOTONIC, &ticks);
    return ticks.tv_sec + ticks.tv_nsec * 1e-9;
#endif
}
/* Time common positive values, wide-exponent positives, and subnormals, rotating three paths and checking checksums. */
static int benchmark(void) {
#ifdef _WIN32
    SetThreadAffinityMask(GetCurrentThread(), 1);
#endif
    const unsigned lengths[] = {60, 110, 120, 128, 220, 240, 256, 440, 480, 512, 960, 1024, 1920};
    for (unsigned range = 0; range < 3; ++range) {
        for (unsigned i = 0; i < 1024; ++i) {
            uint64_t bits = random_bits();
            inputs[i] =
                range == 0
                    ? (double)lengths[i % (sizeof lengths / sizeof *lengths)] * (double)(i + 1)
                : range == 1 ? audio_math_float64_from_bits((bits % UINT64_C(0x7fd0000000000000)) +
                                                      UINT64_C(0x0010000000000000))
                             : audio_math_float64_from_bits((bits & UINT64_C(0x000fffffffffffff)) | 1u);
        }
        for (unsigned round = 0; round < 7; ++round) {
            double times[3];
            uint64_t sums[3];
            for (unsigned visit = 0; visit < 3; ++visit) {
                unsigned side = (visit + round) % 3;
                uint64_t sum = 0;
                double start = now_seconds();
                for (unsigned i = 0; i < 65536; ++i)
                    sum += audio_math_float64_bits(functions[side](inputs[i & 1023]));
                times[side] = now_seconds() - start;
                sums[side] = sum;
                consumed = sum;
            }
            if (sums[0] != sums[1] || sums[0] != sums[2])
                return 1;
            printf("{\"range\":%u,\"round\":%u,\"operations\":65536,\"before\":%.12g,"
                   "\"after\":%.12g,\"software\":%.12g,\"checksum\":\"%016" PRIx64 "\"}\n",
                   range, round, times[0], times[1], times[2], sums[0]);
        }
    }
    return 0;
}
/* Check exceptional inputs, all exponents, subnormals, square boundaries, and random bits.
 * --oracle reads independently correctly-rounded results generated by Python arbitrary-precision integers. */
int main(int argc, char **argv) {
    if (argc == 2 && strcmp(argv[1], "--bench") == 0)
        return benchmark();
    if (argc == 3 && strcmp(argv[1], "--oracle") == 0) {
        FILE *file = fopen(argv[2], "r");
        if (!file)
            return 2;
        uint64_t bits, expected;
        while (fscanf(file, "%" SCNx64 " %" SCNx64, &bits, &expected) == 2) {
            double value = audio_math_float64_from_bits(bits);
            if (audio_math_float64_bits(functions[1](value)) != expected ||
                audio_math_float64_bits(functions[2](value)) != expected) {
                printf("FAIL oracle input=%016" PRIx64 "\n", bits);
                fclose(file);
                return 1;
            }
            ++checks;
        }
        int bad = ferror(file) || !feof(file);
        fclose(file);
        if (bad || !checks)
            return 2;
    } else {
        const uint64_t values[] = {0,
                                   UINT64_C(0x8000000000000000),
                                   1,
                                   UINT64_C(0x8000000000000001),
                                   UINT64_C(0x000fffffffffffff),
                                   UINT64_C(0x0010000000000000),
                                   UINT64_C(0x3ff0000000000000),
                                   UINT64_C(0xbff0000000000000),
                                   UINT64_C(0x4000000000000000),
                                   UINT64_C(0x4010000000000000),
                                   UINT64_C(0x7fefffffffffffff),
                                   UINT64_C(0xffefffffffffffff),
                                   UINT64_C(0x7ff0000000000000),
                                   UINT64_C(0xfff0000000000000),
                                   UINT64_C(0x7ff8123456789abc),
                                   UINT64_C(0xfff8123456789abc),
                                   UINT64_C(0x7ff0123456789abc),
                                   UINT64_C(0xfff0123456789abc),
                                   UINT64_C(0x7ff8fedcba987654),
                                   UINT64_C(0xfff0fedcba987654)};
        for (unsigned i = 0; i < sizeof values / sizeof *values; ++i)
            if (!check_value(values[i]))
                return 1;
        const uint64_t fractions[] = {0, 1, UINT64_C(0x0007ffffffffffff),
                                      UINT64_C(0x000fffffffffffff)};
        for (unsigned exponent = 0; exponent < 2048; ++exponent)
            for (unsigned variant = 0; variant < 8; ++variant)
                if (!check_value(((uint64_t)exponent << 52) | fractions[variant & 3] |
                                 (variant & 4 ? UINT64_C(0x8000000000000000) : 0)))
                    return 1;
        for (uint64_t bits = 0; bits < 65536; ++bits)
            if (!check_value(bits))
                return 1;
        for (unsigned integer = 1; integer < 65536; ++integer) {
            uint64_t square = audio_math_float64_bits((double)integer * integer);
            for (unsigned neighbor = 0; neighbor < 3; ++neighbor)
                if (!check_value(square + neighbor - 1))
                    return 1;
        }
        for (unsigned i = 0; i < 1000000; ++i)
            if (!check_value(random_bits()))
                return 1;
    }
    printf("PASS sqrt64_checks=%" PRIu64 "\n", checks);
    return 0;
}
